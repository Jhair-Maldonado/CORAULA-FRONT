export type StudentLevel = 'PRIMARY' | 'SECONDARY';
// SUSPENDED and DEACTIVATED (permanent) come from BACK #41; WITHDRAWN/GRADUATED keep their meaning.
export type StudentStatus = 'ACTIVE' | 'SUSPENDED' | 'DEACTIVATED' | 'WITHDRAWN' | 'GRADUATED';
export type EnrollmentStatus = 'ACTIVE' | 'WITHDRAWN' | 'COMPLETED';
export type GuardianRelationship = 'FATHER' | 'MOTHER' | 'TUTOR' | 'GUARDIAN' | 'OTHER';

export interface StudentSummaryResponse {
  studentId: number;
  studentCode: string | null;
  dni: string | null;
  firstNames: string;
  paternalLastName: string;
  maternalLastName: string | null;
  birthDate: string | null;
  studentStatus: StudentStatus;
  enrollmentId: number | null;
  enrollmentStatus: EnrollmentStatus | null;
  academicPeriodId: number | null;
  academicPeriodName: string | null;
  sectionId: number | null;
  level: StudentLevel | null;
  grade: number | null;
  sectionName: string | null;
}

export interface GuardianSummaryResponse {
  guardianId: number;
  personId: number;
  dni: string | null;
  firstNames: string;
  paternalLastName: string;
  maternalLastName: string | null;
  phone: string | null;
  relationship: GuardianRelationship;
  primary: boolean;
  authorizedPickup: boolean;
  active: boolean;
}

export interface StudentDetailResponse extends StudentSummaryResponse {
  personId: number;
  phone: string | null;
  enrollmentDate: string | null;
  guardians: GuardianSummaryResponse[];
}

export interface StudentListParams {
  search?: string;
  level?: StudentLevel;
  grade?: number;
  sectionId?: number;
  status?: StudentStatus;
  page?: number;
  size?: number;
}

export interface PagedStudentsResponse {
  content: StudentSummaryResponse[];
  page: number;
  size: number;
  totalElements: number;
  totalPages: number;
}

export interface UpdateStudentRequest {
  studentCode?: string | null;
  dni?: string | null;
  firstNames?: string | null;
  paternalLastName?: string | null;
  maternalLastName?: string | null;
  birthDate?: string | null;
  phone?: string | null;
  // Mandatory for both ADMINISTRADOR and DIRECTIVO (BACK #74).
  reason: string;
}

// studentCode is generated by the backend (BACK #75) and never travels in the create body.
export interface CreateStudentRequest {
  dni: string;
  firstNames: string;
  paternalLastName: string;
  maternalLastName: string | null;
  birthDate: string;
  phone: string | null;
  reason: string;
}

// Basic version: always a new person (personId never travels); the backend has no lookup by DNI.
export interface CreateStudentGuardianRequest {
  dni: string;
  firstNames: string;
  paternalLastName: string;
  maternalLastName: string | null;
  phone: string | null;
  relationship: GuardianRelationship;
  primary: boolean;
  authorizedPickup: boolean;
  reason: string;
}

// PATCH /students/{id}/suspend | reactivate | deactivate (BACK #41); ADMINISTRADOR only.
export type StudentStateAction = 'SUSPEND' | 'REACTIVATE' | 'DEACTIVATE';
export type StudentStateReasonCode =
  | 'ADMINISTRATIVE_REVIEW' | 'GUARDIAN_REQUEST'
  | 'SUSPENSION_RESOLVED' | 'ADMINISTRATIVE_CORRECTION'
  | 'VOLUNTARY_WITHDRAWAL' | 'TRANSFER' | 'DUPLICATE_RECORD' | 'ERRONEOUS_RECORD'
  | 'OTHER';

export interface ChangeStudentStateRequest {
  reasonCode: StudentStateReasonCode;
  // Not blank, up to 1000 characters.
  justification: string;
}

export interface StudentStateChangeResponse {
  studentId: number;
  previousStatus: StudentStatus;
  studentStatus: StudentStatus;
  reasonCode: StudentStateReasonCode;
  justification: string;
  changedBy: number;
  changedAt: string;
  // null when the student has no linked account.
  accountEnabled: boolean | null;
}
